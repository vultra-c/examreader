# JSON 文件格式说明

## 一句话原理

整个文件是一个**大括号对象**——键是科目名，值是该科目下的条目数组。

```json
{ "我的笔记": [ { "title": "勾股定理" } ] }
```

推送到手环后，科目列表里就会多出一个叫「我的笔记」的科目，里面包含一条「勾股定理」。

---

## 最小可用写法

```json
{ "科目名": [ { "title": "条目标题" } ] }
```

其中 `title` 是**唯一必填字段**，其余字段缺失时均有安全兜底，不会导致报错。

---

## 字段说明

**`title`（必填）**
条目标题。缺失则该条目被丢弃。

**`id`（可选）**
条目编号。缺省时自动按数组顺序从 1 开始编号。同科目内按 id 去重。

**`desc`（可选）**
简介内容，显示在标题下方。

**`points`（可选）**
速记要点列表，每个字符串为一条要点。类型为字符串数组。

**`raw`（可选）**
整段原文，会自动按行分段、按字数分页显示。

**`formulas`（可选）**
公式列表。推送完成后系统会自动渲染为公式图并传至手环，详见《公式推送指南》。类型为字符串数组。

---

## 与内置知识库的合并规则

**科目名与手环自带科目相同（如「语文」）**
按 `id` 进行合并。若编号与内置条目冲突，**内置条目优先**，导入条目会被跳过。
> 如需为内置科目补充内容，建议使用较大的 id 值（如 10001）以避免冲突。

**科目名手环中不存在（如「拓展物理」）**
整个科目作为新科目添加，首页会标注「导入」字样，并排列在自带科目之后。

**同一文件内出现重复（同科目 + 同 id）**
以**最后出现**的条目为准。重复推送同一文件不会导致条目数量翻倍（幂等）。

---

## 文件格式要求

- **编码**：必须为 UTF-8（无 BOM），中文可直接书写，无需转义。
- **扩展名**：保存为 `.json` 文件。
- **大小限制**：无硬性上限，从几 KB 到几百 KB 均可，手机端会自动分片传输。

---

## 完整写法示例

```json
{
  "拓展物理": [
    {
      "id": 1,
      "title": "相对论初步",
      "desc": "狭义相对论的基本假设与时间膨胀效应。",
      "raw": "狭义相对论建立在两条基本假设之上……",
      "points": [
        "光速不变原理",
        "相对性原理",
        "运动钟变慢"
      ],
      "formulas": [
        "t = t0 / sqrt(1 - v^2/c^2)"
      ]
    }
  ]
}
```

---

## 推送后未出现的常见原因

以下情况**不会报错**，仅对应内容被静默忽略。如发现内容未显示，请逐一核对：

**顶层是数组而非对象**
正确写法应为 `{ ... }`，而非 `[ ... ]`。

**条目缺少 `title`**
无标题的条目会被丢弃。

**`id` 与内置条目冲突**
导入的条目会被跳过（内置优先）。

**`points` 是字符串而非数组**
应写为 `["要点1", "要点2"]` 而非 `"要点1, 要点2"`。

**文件编码非 UTF-8**
中文乱码或解析失败，请用 UTF-8（无 BOM）保存。
""".trimIndent()
